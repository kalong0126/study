/**
 * 组装 user 消息：本次调用约定 + 已读主题去重列表。
 *
 * 「本次调用约定」是**必要的工程补充**：文档默认会附带阅读训练内容、也可能被要求输出 JSON，
 * 但这个应用只要正文 —— 正文要存库、要逐句朗读给孩子听，多一行【好词积累】都会被读出来。
 * 所以在这里把产物格式钉死（不改变上面任何一条创作要求，只约束「输出什么」）。
 *
 * 去重列表同样放在 user 消息里，且**只在非空时追加**（首次生成不能出现这段，
 * server/test/api.test.ts 的 C6/C9 两条断言盯着它）。
 */
export function buildStoryPrompt(avoidTitles: string[] = []): string {
  const lines = [
    "本次调用约定（只发故事本身，覆盖上面文档里的输出格式与附加内容要求）：",
    "1. 不要输出 JSON、Markdown、代码块，也不要写任何解释性文字。",
    "2. 不要输出【好词积累】【好句积累】【阅读理解】【表达训练】这类附加内容 —— 这一篇只给孩子朗读，正文之外不要有任何文字。",
    "3. 第一行只写故事标题，用《》括起来，8～16 个汉字，按「角色 + 事件」来起。",
    "4. 从第二行开始写正文，正文**严格**分成 5～8 个自然段（不要把对话、动作单独拆成一段），段落之间空一行。",
    "5. 正文不要出现英文字母、阿拉伯数字、表情符号、【】小标题或 Markdown 标记。",
    "6. 正文控制在 600～700 个汉字，目标 650 字，不足 600 字视为不合格。",
  ];
  const avoid = avoidTitles.filter((t) => t && !t.startsWith("示例：")).slice(-40);
  if (avoid.length) {
    lines.push("");
    lines.push(`请不要创作以下主题：[${avoid.join("、")}]`);
  }
  return lines.join("\n");
}

export interface ParsedStory {
  title: string;
  text: string;
}

/**
 * 解析模型输出。
 * 正常情况：第一行是《标题》，其余是正文。
 * 兜底：万一模型没按格式来（直接写正文），沿用旧行为——截取开头 12 字当标题。
 */
export function parseStory(raw: string): ParsedStory {
  const text = String(raw || "").trim();
  if (!text) return { title: "", text: "" };

  const lines = text.split(/\r?\n/);
  const firstIdx = lines.findIndex((l) => l.trim().length > 0);
  if (firstIdx < 0) return { title: "", text: "" };

  const first = lines[firstIdx].trim();
  const rest = lines
    .slice(firstIdx + 1)
    .join("\n")
    .trim();

  // 形如 《小水滴的旅行》
  const m = first.match(/^[#\s]*[《【\[]?\s*([^》】\]]{1,20})\s*[》】\]]?$/);
  if (rest && first.includes("《") && m) {
    return { title: m[1].trim(), text: rest };
  }
  // 形如 "标题：小水滴的旅行"
  const m2 = first.match(/^(?:标题|题目)[:：]\s*(.+)$/);
  if (rest && m2) {
    return { title: m2[1].replace(/[《》]/g, "").trim(), text: rest };
  }

  // 兜底：模型没给标题，沿用旧版逻辑
  const flat = text.replace(/\s+/g, "");
  const title = flat.slice(0, 12) + (flat.length > 12 ? "…" : "");
  return { title, text };
}
